export const H = 26;
const inside = (w, fns) => Array.from({length: H}, (_, y) =>
  Array.from({length: w}, (_, x) => fns.some(f => f(x + 0.5, y + 0.5)) ? '#' : '.').join(''));
export const box = (x0, y0, x1, y1) => (x, y) => x >= x0 && x < x1 && y >= y0 && y < y1;
export const seg = (x0, y0, x1, y1, hw = 4.6) => (x, y) => {
  const dx = x1 - x0, dy = y1 - y0, t = Math.max(0, Math.min(1, ((x-x0)*dx + (y-y0)*dy) / (dx*dx + dy*dy)));
  return Math.hypot(x - (x0 + t*dx), y - (y0 + t*dy)) <= hw;
};
// a thick elliptical ring between outer radii (rx, ry) and inner (rx - tx, ry - ty), over an angle range
export const ring = (cx, cy, rx, ry, tx, ty, a0 = 0, a1 = 360) => (x, y) => {
  const o = ((x-cx)/rx)**2 + ((y-cy)/ry)**2, i = ((x-cx)/(rx-tx))**2 + ((y-cy)/(ry-ty))**2;
  if(o > 1 || i < 1) return false;
  let d = Math.atan2(y - cy, x - cx) * 180 / Math.PI; if(d < 0) d += 360;
  return a0 <= a1 ? d >= a0 && d <= a1 : d >= a0 || d <= a1;
};
export const minus = (f, g) => (x, y) => f(x, y) && !g(x, y);

