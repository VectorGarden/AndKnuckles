/* 9 is the 6 turned 180 degrees. Hand-drawing it separately gave the tail a
   down-left sweep against a full-width chamfered base, and the two fought each
   other into a step on the bottom-right edge. Deriving it guarantees the two
   glyphs share one contour. */
const rot180 = rows => rows.slice().reverse().map(r => [...r].reverse().join(''));
DIGITS['9'] = rot180(DIGITS['6']);
